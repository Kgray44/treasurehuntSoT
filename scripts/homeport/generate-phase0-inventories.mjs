function entryMatches(pattern, destination) {
  const escaped = pattern
    .split("/")
    .map((segment) =>
      segment.startsWith(":")
        ? "[^/]+"
        : segment.startsWith("*")
          ? ".*"
          : segment.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&"),
    )
    .join("/");
  return new RegExp(`^${escaped}$`, "u").test(destination);
}

