function defaultParent(pathPattern) {
  if (Object.hasOwn(parentOverrides, pathPattern)) return parentOverrides[pathPattern];
  if (pathPattern.startsWith("/account/")) return "/account";
  if (pathPattern.startsWith("/passport/")) return "/passport";
  if (pathPattern.startsWith("/community/")) return "/community";
  if (pathPattern.startsWith("/studio/private-content/")) return "/studio/private-content";
  if (pathPattern.startsWith("/studio/")) return "/studio/library";
  return "/";
}

function authenticationFor(pathPattern, classification) {
  if (classification === "TOKENIZED_DEEP_LINK") return "BOUNDED_TOKEN_OR_CODE";
  if (pathPattern === "/community/moderation" || pathPattern === "/community/moderation/[id]")
    return "AUTHENTICATED_CAPABILITY_REQUIRED";
  if (pathPattern.startsWith("/community/voyage-logs/owner") || pathPattern.endsWith("/consent"))
    return "AUTHENTICATED_ACCOUNT_REQUIRED";
  if (pathPattern === "/studio/private-content/operations") return "AUTHENTICATED_CAPABILITY_REQUIRED";
  if (/^\/(?:account|passport)(?:\/|$)/u.test(pathPattern)) return "AUTHENTICATED_ACCOUNT_REQUIRED";
  if (/^\/(?:captain|quartermaster)(?:\/|$)/u.test(pathPattern) && !pathPattern.endsWith("/sign-in"))
    return "AUTHENTICATED_CAPABILITY_REQUIRED";
  if (/^\/studio(?:\/|$)/u.test(pathPattern) && !pathPattern.endsWith("/sign-in"))
    return "AUTHENTICATED_CAPABILITY_REQUIRED";
  if (/^\/player(?:\/|$)/u.test(pathPattern) && !pathPattern.endsWith("/sign-in"))
    return "AUTHENTICATED_PLAYER_REQUIRED";
  return "ANONYMOUS_ALLOWED";
}

function capabilitiesFor(pathPattern) {
  if (pathPattern === "/community/moderation" || pathPattern === "/community/moderation/[id]") return ["MODERATOR"];
  if (pathPattern === "/studio/private-content/operations") return ["ADMINISTRATOR"];
  if (pathPattern.startsWith("/community/voyage-logs/owner") || pathPattern.endsWith("/consent")) return ["PLAYER"];
  if (/^\/(?:captain|quartermaster)(?:\/|$)/u.test(pathPattern) && !pathPattern.endsWith("/sign-in"))
    return ["CAPTAIN"];
  if (/^\/studio(?:\/|$)/u.test(pathPattern) && !pathPattern.endsWith("/sign-in")) return ["CREATOR"];
  if (/^\/player(?:\/|$)/u.test(pathPattern) && !pathPattern.endsWith("/sign-in")) return ["PLAYER"];
  return [];
}

function navigationOwnerFor(pathPattern) {
  if (pathPattern === "/") return "GLOBAL";
  if (pathPattern.startsWith("/account") || pathPattern.startsWith("/passport")) return "PERSONAL_HARBOR_SECTION";
  if (pathPattern.startsWith("/community")) return "COMMUNITY_DISTRICT_OR_CONTEXT";
  if (pathPattern.startsWith("/player")) return "PLAYER_WORKSPACE_OR_CONTEXT";
  if (pathPattern.startsWith("/captain") || pathPattern.startsWith("/quartermaster"))
    return "CAPTAIN_WORKSPACE_OR_CONTEXT";
  if (pathPattern.startsWith("/studio")) return "CREATOR_WORKSPACE_OR_CONTEXT";
  if (pathPattern.startsWith("/play") || pathPattern.startsWith("/tale") || pathPattern === "/tales")
    return "CHRONICLE_DISCOVERY_OR_CONTEXT";
  return "GLOBAL_OR_ACCOUNT_LIFECYCLE";
}

