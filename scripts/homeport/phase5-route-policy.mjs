export function nodePolicy(pathPattern, base = {}) {
  const classification = classificationForPath(pathPattern);
  const authentication = authenticationFor(pathPattern, classification);
  const requiredCapabilities = capabilitiesFor(pathPattern);
  const parent = defaultParent(pathPattern);
  const returnFallback =
    classification === "REDIRECT_ALIAS" || classification === "AUTH_COMPATIBILITY_ALIAS"
      ? (canonicalOverrides[pathPattern] ?? parent)
      : parent;
  return {
    classification,
    logicalParent: parent,
    canonicalRoute: canonicalOverrides[pathPattern] ?? pathPattern,
    activeNavigationOwner: navigationOwnerFor(pathPattern),
    authentication,
    requiredCapabilities,
    anonymousAvailability: authentication === "ANONYMOUS_ALLOWED" || authentication === "BOUNDED_TOKEN_OR_CODE",
    desktopAvailability: true,
    mobileAvailability: true,
    compactOrImmersive: ["COMPACT", "IMMERSIVE"].includes(base.shellMode) ? base.shellMode : "NO",
    dynamicSourceRequired: classification === "CONTEXTUAL_DYNAMIC",
    tokenized: classification === "TOKENIZED_DEEP_LINK",
    compatibility: ["AUTH_COMPATIBILITY_ALIAS", "REDIRECT_ALIAS"].includes(classification),
    deprecated: classification === "DEPRECATED",
    sourceCollectionIds: dynamicSourceIds[pathPattern] ?? [],
    returnFallback,
    currentDisposition:
      classification === "USER_NAVIGABLE"
        ? requiredCapabilities.length
          ? "REACHABLE_PERMISSION_GATED"
          : "REACHABLE"
        : classification === "CONTEXTUAL_DYNAMIC"
          ? requiredCapabilities.length
            ? "REACHABLE_PERMISSION_GATED"
            : "REACHABLE_CONTEXTUAL"
          : classification === "TOKENIZED_DEEP_LINK"
            ? "INTENTIONALLY_TOKENIZED"
            : ["AUTH_COMPATIBILITY_ALIAS", "REDIRECT_ALIAS"].includes(classification)
              ? "INTENTIONALLY_COMPATIBILITY_ONLY"
              : classification === "DEVELOPMENT_ONLY"
                ? "INTENTIONALLY_DEVELOPMENT_ONLY"
                : classification === "INTERNAL_DIAGNOSTIC"
                  ? "OWNER_ONLY_DIAGNOSTIC"
                  : "DEPRECATED_WITH_DISPOSITION",
  };
}

